import os
import logging
import requests
import tempfile
from openai import OpenAI
from db.supabase import get_supabase_client
from services.exotel_service import _get_exotel_creds

logger = logging.getLogger(__name__)

def process_call_recording(appointment_id: str, recording_url: str):
    """
    Background task to download an Exotel call recording, transcribe it via Whisper,
    summarize it via GPT-4o-mini, and save the result to the patient's timeline or appointment notes.
    """
    logger.warning(f"Starting process_call_recording for appointment {appointment_id}. URL: {recording_url}")
    
    # 1. Download the recording audio
    try:
        creds = _get_exotel_creds()
        response = requests.get(
            recording_url, 
            stream=True, 
            auth=(creds.get('api_key', ''), creds.get('token', ''))
        )
        response.raise_for_status()
    except Exception as e:
        logger.error(f"Failed to download recording from {recording_url}: {e}")
        return
        
    # Exotel recordings are usually .wav or .mp3
    suffix = ".mp3"
    content_type = response.headers.get("content-type", "")
    if "wav" in content_type:
        suffix = ".wav"
        
    temp_path = ""
    try:
        with tempfile.NamedTemporaryFile(suffix=suffix, delete=False) as temp_audio:
            for chunk in response.iter_content(chunk_size=8192):
                temp_audio.write(chunk)
            temp_path = temp_audio.name
            
        logger.warning(f"Audio downloaded to temp file: {temp_path}")
        
        # 2. Transcribe via Deepgram (if available) or Whisper
        dg_api_key = os.getenv("DEEPGRAM_API_KEY")
        transcription_text = ""
        
        client = OpenAI(api_key=os.getenv("OPENAI_API_KEY"))
        if dg_api_key:
            logger.warning("Using Deepgram for transcription...")
            url = "https://api.deepgram.com/v1/listen?model=nova-2&language=hi&smart_format=true&punctuate=true&diarize=true&keywords=paracetamol:2&keywords=blood+pressure:2&keywords=sugar:2&keywords=prescription:2&keywords=ECG:2"
            headers = {
                "Authorization": f"Token {dg_api_key}"
            }
            with open(temp_path, "rb") as audio_file:
                audio_data = audio_file.read()
            dg_response = requests.post(url, headers=headers, data=audio_data)
            dg_response.raise_for_status()
            dg_result = dg_response.json()
            try:
                transcription_text = dg_result["results"]["channels"][0]["alternatives"][0]["transcript"]
            except KeyError:
                transcription_text = ""
        else:
            logger.warning("DEEPGRAM_API_KEY not found. Falling back to Whisper...")
            with open(temp_path, "rb") as audio_file:
                transcript = client.audio.transcriptions.create(
                    model="whisper-1", 
                    file=audio_file
                )
            transcription_text = transcript.text
        logger.warning(f"""Transcription successful. Length: {len(transcription_text)}
RAW TRANSCRIPT:
{transcription_text}
====================""")
        
        # 3. Summarize via OpenAI GPT-4o-mini
        completion = client.chat.completions.create(
            model="gpt-4o-mini",
            response_format={ "type": "json_object" },
            messages=[
                {
                    "role": "system",
                    "content": (
                        "You are an expert medical scribe in India. You will be provided with a transcript of a telehealth call between a doctor and a patient. "
                        "The transcript is in Hinglish (a mix of Hindi and English) and was generated by AI, so it may contain phonetic spelling errors, missing words, or misunderstood medical terms.\n\n"
                        "Your task is to:\n"
                        "1. Look past minor transcription errors using your medical context. Provide a structured summary IN ENGLISH including: Chief Complaint, Symptoms, Diagnosis/Assessment, and Prescribed Treatment/Next Steps.\n"
                        "2. Identify who is the Doctor (usually giving advice/asking symptoms) and who is the Patient. Reformat the raw transcript into a readable conversation with speakers (e.g., Doctor: ..., Patient: ...). DO NOT paraphrase or translate the dialogue! Keep the EXACT ORIGINAL WORDS (including Hindi/Hinglish). Only add speaker labels.\n\n"
                        "Return your response in JSON format with exactly two keys: 'summary' (a string) and 'formatted_transcript' (a string)."
                    )
                },
                {"role": "user", "content": transcription_text}
            ]
        )

        import json
        result = json.loads(completion.choices[0].message.content)
        summary = result.get('summary', '')
        formatted_transcript = result.get('formatted_transcript', transcription_text)
        logger.warning("Summary and formatted transcript generated successfully.")
        
        # 4. Save to Database
        content = f"**📞 Call Summary**\n\n{summary}\n\n[▶️ Listen to Recording]({recording_url})\n\n||TRANSCRIPT||\n{formatted_transcript}"
        
        supabase = get_supabase_client()
        
        # Fetch the appointment to get the patient_id
        res = supabase.table('appointments').select('*').eq('id', appointment_id).execute()
        if not res.data:
            logger.error(f"Appointment {appointment_id} not found in DB")
            return
            
        appt = res.data[0]
        patient_id = appt.get('patient_id')
        
        if patient_id and str(patient_id) != 'null':
            # Save to patient's timeline (Update if exists)
            existing = supabase.table("communications").select("*").eq("lead_id", patient_id).eq("type", "call").ilike("content", f"%{recording_url}%").execute()
            if existing.data:
                supabase.table("communications").update({"content": content}).eq("id", existing.data[0]['id']).execute()
                logger.warning(f"Updated existing call summary for patient {patient_id}")
            else:
                supabase.table("communications").insert({
                    "lead_id": patient_id,
                    "type": "call",
                    "content": content
                }).execute()
                logger.warning(f"Inserted new call summary for patient {patient_id}")
        else:
            # Fallback for unlinked appointments (AI voice booking)
            existing_notes = appt.get('notes') or ""
            import datetime
            import re
            timestamp = f"[{datetime.datetime.now().strftime('%Y-%m-%d %H:%M')}] Note added:\n"
            
            if recording_url in existing_notes:
                # Replace the old chunk that had this recording
                chunks = re.split(r'\n\n(?=\[\d{4}-\d{2}-\d{2} \d{2}:\d{2}\] Note added:\n)', existing_notes)
                new_chunks = []
                replaced = False
                for chunk in chunks:
                    if recording_url in chunk:
                        new_chunks.append(timestamp + content)
                        replaced = True
                    else:
                        new_chunks.append(chunk)
                if not replaced:
                    new_chunks.append(timestamp + content)
                new_notes = "\n\n".join(new_chunks).strip()
            else:
                new_notes = (existing_notes + "\n\n" + timestamp + content).strip()
                
            supabase.table('appointments').update({'notes': new_notes}).eq('id', appointment_id).execute()
            logger.warning(f"Saved call summary to appointment notes for {appointment_id}")
            
    except Exception as e:
        logger.error(f"Error processing call recording for appointment {appointment_id}: {e}")
    finally:
        if temp_path and os.path.exists(temp_path):
            os.remove(temp_path)
